#!/usr/bin/env bash
#
# Regenerates the vendored manifests behind par's simulated GPUs (use case 4):
#
#   gitops/manifests/scheduling/sim-gpu/kwok/kwok-v0.8.0.yaml
#       the KWOK controller release manifest, verbatim
#   gitops/manifests/scheduling/sim-gpu/kwok/stages-v0.8.0.yaml
#       KWOK's stage-fast.yaml without its pod-complete stage, so a Job pod
#       on a KWOK node stays Running until the demo deletes it, the way a
#       training pod would, instead of reading Succeeded a second after start
#   gitops/manifests/scheduling/sim-gpu/fake-gpu/fake-gpu-operator-0.2.1.yaml
#       run-ai/fake-gpu-operator rendered with
#       gitops/values/scheduling/fake-gpu-operator.yaml, CRDs skipped
#
# Why vendored and not synced as a chart: neither project exposes a
# nodeSelector for its Deployments, and par's control plane is untainted, so
# the kustomizations next to these files add eu1.io/pool: cpu and pin images
# by digest. Run it after changing a version or the values, then commit the
# result. Running it twice with the same inputs changes nothing.
#

source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"

require_tools helm curl awk

KWOK_VERSION=v0.8.0
FGO_VERSION=0.2.1
OUT="$REPO_ROOT/gitops/manifests/scheduling/sim-gpu"
KWOK_URL="https://github.com/kubernetes-sigs/kwok/releases/download/$KWOK_VERSION"

header() {
  printf '# GENERATED by scripts/scheduling/render-sim-gpu.sh from %s.\n' "$1"
  printf '# SIMULATED GPUs for use case 4 on par, see docs/simulated.md. Do not edit.\n'
}

log "KWOK $KWOK_VERSION controller"
{
  header "$KWOK_URL/kwok.yaml"
  curl -sSfL "$KWOK_URL/kwok.yaml"
} > "$OUT/kwok/kwok-$KWOK_VERSION.yaml"

log "KWOK $KWOK_VERSION stages, without pod-complete"
{
  header "$KWOK_URL/stage-fast.yaml, minus the pod-complete Stage"
  curl -sSfL "$KWOK_URL/stage-fast.yaml" | awk '
    function flush() { if (doc != "" && doc !~ /\n  name: pod-complete\n/) printf "%s", doc; doc = "" }
    /^---$/ { flush(); doc = "---\n"; next }
    { doc = doc $0 "\n" }
    END { flush() }'
} > "$OUT/kwok/stages-$KWOK_VERSION.yaml"
if grep -q 'name: pod-complete' "$OUT/kwok/stages-$KWOK_VERSION.yaml"; then
  die "pod-complete stage still present"
fi

log "fake-gpu-operator $FGO_VERSION"
# Pulled first, because helm template prints "Pulled:" and "Digest:" on stdout
# when it fetches an OCI chart itself. The digest goes in the header instead.
chart_dir="$(mktemp -d)"
trap 'rm -rf "$chart_dir"' EXIT
chart_digest="$(helm pull oci://ghcr.io/run-ai/fake-gpu-operator/fake-gpu-operator \
  --version "$FGO_VERSION" --untar --untardir "$chart_dir" 2>&1 \
  | awk '/^Digest:/ {print $2}')"
[ -n "$chart_digest" ] || die "no chart digest from helm pull"
{
  header "oci://ghcr.io/run-ai/fake-gpu-operator/fake-gpu-operator $FGO_VERSION@$chart_digest"
  helm template fake-gpu "$chart_dir/fake-gpu-operator" \
    --namespace fake-gpu --skip-crds \
    -f "$REPO_ROOT/gitops/values/scheduling/fake-gpu-operator.yaml"
} > "$OUT/fake-gpu/fake-gpu-operator-$FGO_VERSION.yaml"

log "done; review with git diff $OUT"
