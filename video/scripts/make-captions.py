#!/usr/bin/env python3
"""Generate the burned-in captions of the 1:1 cut (compositions/sq/captions.html) and the
WebVTT track of the 16:9 master (docs/assets/video/nordhaven.vtt).

Reads each narration line's word timings (assets/voice/sNN.words.json), groups them in
3 to 5 words (breaking at punctuation), and places each group at its scene start +
VO + the word's time, one group on screen at a time, in the bottom band.

    python3 scripts/make-captions.py
"""
import html
import json
import pathlib

from cuts import MASTER, SQUARE, VO, starts

root = pathlib.Path(__file__).resolve().parent.parent
MAX_WORDS = 5

def group_words(slots):
    """Caption groups for one cut: (start, end, text), one on screen at a time."""
    at, _ = starts(slots)
    raw = []
    for sid, _ in slots:
        words = json.loads((root / f"assets/voice/{sid}.words.json").read_text())["words"]
        # Phrases end at punctuation; a long phrase splits into balanced chunks of at most
        # MAX_WORDS, so no group is left with a single straggling word.
        phrases, cur = [], []
        for w in words:
            cur.append(w)
            if w["word"][-1] in ".,:;?!":
                phrases.append(cur)
                cur = []
        if cur:
            phrases.append(cur)
        for ph in phrases:
            n = -(-len(ph) // MAX_WORDS)
            size = -(-len(ph) // n)
            for k in range(0, len(ph), size):
                ws = ph[k:k + size]
                base = at[sid] + VO
                raw.append([round(base + ws[0]["start"] - 0.05, 2), round(base + ws[-1]["end"] + 0.15, 2),
                            " ".join(w["word"] for w in ws)])
    for i in range(len(raw) - 1):  # never overlap the next group
        raw[i][1] = min(raw[i][1], round(raw[i + 1][0] - 0.02, 2))
    return raw


def vtt_time(t):
    h, rem = divmod(t, 3600)
    m, sec = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{sec:06.3f}"


# WebVTT track for the 16:9 master on the docs site.
vtt = ["WEBVTT", ""]
for i, (a, b, text) in enumerate(group_words(MASTER), 1):
    vtt += [str(i), f"{vtt_time(a)} --> {vtt_time(b)}", text, ""]
(root.parent / "docs/assets/video/nordhaven.vtt").write_text("\n".join(vtt))

at, total = starts(SQUARE)
groups = group_words(SQUARE)
items, tweens = [], []
for i, (start, end, text) in enumerate(groups):
    items.append(f'          <div class="cap" id="cap{i:03d}"><span>{html.escape(text)}</span></div>')
    tweens.append(f'          tl.fromTo("#cap{i:03d}", {{ opacity: 0, y: 8 }}, {{ opacity: 1, y: 0, duration: 0.12, ease: "power2.out" }}, {start});\n'
                  f'          tl.to("#cap{i:03d}", {{ opacity: 0, duration: 0.1, ease: "power2.in" }}, {round(end - 0.1, 2)});\n'
                  f'          tl.set("#cap{i:03d}", {{ visibility: "hidden" }}, {end});')

doc = f"""<!doctype html>
<!-- Generated by scripts/make-captions.py from assets/voice/*.words.json. Do not edit. -->
<html>
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <template>
      <style>
        #captions-root {{
          position: absolute;
          inset: 0;
        }}
        #captions-root .cap {{
          position: absolute;
          left: 0;
          right: 0;
          bottom: 96px;
          text-align: center;
          opacity: 0;
          overflow: visible;
        }}
        #captions-root .cap span {{
          display: inline-block;
          max-width: 940px;
          padding: 8px 18px;
          border-radius: 12px;
          background: rgba(11, 14, 12, 0.72);
          font-family: var(--sans);
          font-weight: 700;
          font-size: 44px;
          line-height: 1.15;
          letter-spacing: -0.01em;
          color: #f2f5ee;
        }}
      </style>
      <div id="captions-root" data-composition-id="captions" data-width="1080" data-height="1080">
{chr(10).join(items)}
      </div>
      <script>
        (function () {{
          const tl = gsap.timeline({{ paused: true }});
{chr(10).join(tweens)}
          window.__timelines["captions"] = tl;
        }})();
      </script>
    </template>
  </body>
</html>
"""
(root / "compositions/sq/captions.html").write_text(doc)
print(f"{len(groups)} caption groups over {total} s")
